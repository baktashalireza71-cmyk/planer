export interface FalOfTheDay {
  text: string;
  index: number;
  luckyNumber: number;
  luckyColor: LuckyColor;
}

/**
 * فال روزانه یک برج شمسی — کاملاً قطعی:
 * با (سال، ماه، روز) شمسی، همیشه همان متن/عدد شانس/رنگ شانس برمی‌گردد.
 */
export function getFalOfTheDay(
  jy: number,
  jm: number,
  jd: number
): FalOfTheDay {
  const mf = MONTH_FALS[Math.min(12, Math.max(1, jm)) - 1];
  // هش قطعی روز بر اساس تاریخ شمسی
  const h = jy * 372 + (jm - 1) * 31 + jd;
  const index = (((h % mf.texts.length) + mf.texts.length) % mf.texts.length);
  const luckyNumber = 1 + (((h % 99) + 99) % 99);
  const cHash =
    (((h * 7 + jm * 13 + jd * 3) % LUCKY_COLORS.length) + LUCKY_COLORS.length) %
    LUCKY_COLORS.length;
  return {
    text: mf.texts[index],
    index,
    luckyNumber,
    luckyColor: LUCKY_COLORS[cHash],
  };
}


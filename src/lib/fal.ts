/**
 * سن دقیق شمسی با منطق قرض‌گیری درست ماه/روز:
 * ابتدا کسری روز با طول ماهِ قبلِ «امروز» جبران می‌شود، سپس کسری ماه.
 */
export function jalaliAgeParts(
  birth: JalaliDate,
  today: JalaliDate
): { years: number; months: number; days: number } {
  let years = today.jy - birth.jy;
  let months = today.jm - birth.jm;
  let days = today.jd - birth.jd;

  if (days < 0) {
    months -= 1;
    // قرض‌گیری از ماه قبلِ امروز
    let pm = today.jm - 1;
    let py = today.jy;
    if (pm < 1) {
      pm = 12;
      py -= 1;
    }
    days += jalaliMonthLength(py, pm);
  }
  if (months < 0) {
    years -= 1;
    months += 12;
  }
  return {
    years: Math.max(0, years),
    months: Math.max(0, months),
    days: Math.max(0, days),
  };
}

/** روزِ سال شمسی (۱ فروردین = ۱) */
function jalaliDayOfYear(jy: number, jm: number, jd: number): number {
  let doy = jd;
  for (let m = 1; m < jm; m++) doy += jalaliMonthLength(jy, m);
  return doy;
}

/**
 * فاصله تا تولد بعدی (بر اساس همان روز شمسی):
 * رخداد بعدیِ ماه/روز تولد محاسبه می‌شود؛ روز ۳۰ اسفند در سال غیرکبیسه
 * با jalaliMonthLength مهار می‌شود. «امروز» = صفر.
 */
export function daysUntilNextJalaliBirthday(
  birth: { jm: number; jd: number },
  today: JalaliDate
): number {
  // مهار روز نامعتبر (مثل ۳۰ اسفند در سال غیرکبیسه)
  const lenThis = jalaliMonthLength(today.jy, birth.jm);
  const occThis = Math.min(birth.jd, lenThis);
  const todayDoy = jalaliDayOfYear(today.jy, today.jm, today.jd);
  const thisDoy = jalaliDayOfYear(today.jy, birth.jm, occThis);

  if (thisDoy === todayDoy) return 0;
  if (thisDoy > todayDoy) return thisDoy - todayDoy;

  // تولد امسال گذشته — رخداد سال بعد
  const lenNext = jalaliMonthLength(today.jy + 1, birth.jm);
  const occNext = Math.min(birth.jd, lenNext);
  const nextDoy = jalaliDayOfYear(today.jy + 1, birth.jm, occNext);
  const daysInThisYear = jalaliDayOfYear(
    today.jy,
    12,
    jalaliMonthLength(today.jy, 12)
  );
  return daysInThisYear - todayDoy + nextDoy;
}

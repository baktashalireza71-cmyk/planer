/** تعطیلی رسمی این روز را برمی‌گرداند (یا null اگر تعطیل نباشد) */
export function getIranianHoliday(date: Date): IranianHoliday | null {
  const tj = toJalali(date);
  const solar = SOLAR_HOLIDAYS[`${tj.jm}-${tj.jd}`];
  if (solar) return { title: solar.title, kind: "solar" };
  return LUNAR_INDEX.get(dayKey(date)) ?? null;
}

export interface HolidayOnDate {
  date: Date;
  holiday: IranianHoliday;
}

/** تعطیلات در یک بازه — کلید map همان dayKey میلادی است */
export function getHolidaysInRange(start: Date, end: Date): Map<string, IranianHoliday> {
  const map = new Map<string, IranianHoliday>();
  const d = new Date(start.getFullYear(), start.getMonth(), start.getDate());
  const stop = new Date(end.getFullYear(), end.getMonth(), end.getDate());
  while (d <= stop) {
    const h = getIranianHoliday(d);
    if (h) map.set(dayKey(d), h);
    d.setDate(d.getDate() + 1);
  }
  return map;
}

/** تعطیلات رسمی پیش‌رو از یک تاریخ به بعد */
export function upcomingIranianHolidays(from: Date, limit = 4): HolidayOnDate[] {
  const out: HolidayOnDate[] = [];
  const d = new Date(from.getFullYear(), from.getMonth(), from.getDate());
  // تعطیلات خورشیدی همیشه پوشش داده می‌شوند؛ برای قمری جستجو را محدود می‌کنیم
  for (let i = 0; i < 500 && out.length < limit; i++) {
    const h = getIranianHoliday(d);
    if (h) out.push({ date: new Date(d), holiday: h });
    d.setDate(d.getDate() + 1);
  }
  return out;
}
